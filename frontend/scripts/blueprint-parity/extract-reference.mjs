// Extracts the original design prototype's drawing generator into reference-build.cjs.
//   node scripts/blueprint-parity/extract-reference.mjs path/to/Main.dc.html
// The result is committed so the parity check does not need the design file.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) throw new Error("usage: extract-reference.mjs <Main.dc.html>");
const html = readFileSync(src, "utf8");
const start = html.indexOf("  zoneDefs() {");
const end = html.indexOf("  renderVals() {");
if (start < 0 || end < 0 || end < start) throw new Error("prototype layout changed");
const sha = createHash("sha256").update(html).digest("hex");
const out = `// GENERATED by extract-reference.mjs from the onboarding design prototype (sha256 ${sha}).
// Frozen reference for the parity check. Do not edit.
module.exports = class Reference {
${html.slice(start, end)}
};
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "reference-build.cjs"), out);
console.log("wrote reference-build.cjs", out.length, "bytes");
